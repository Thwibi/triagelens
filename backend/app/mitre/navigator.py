"""ATT&CK Navigator layer generation (spec 08 section 3).

One entry per (technique, tactic) pair an alert mapped to. Score is the
max severity ordinal among the linked alerts (informational 1, low 1,
medium 2, high 3, critical 4). A sub-technique alert also emits its
parent's entry, with the comment prefixed ``via sub-technique`` when the
parent has no direct alerts of its own.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

from app.mitre.matrix import AlertMapping
from app.util.time import utc_now_iso
from app.version import APP_VERSION, ATTACK_DOMAIN, NAVIGATOR_LAYER_VERSION, NAVIGATOR_VERSION

#: Spec 08 section 3: severity ordinals for the layer ``score`` field.
_NAVIGATOR_SCORES: dict[str, int] = {
    "informational": 1,
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}

_PLATFORMS = [
    "Windows",
    "Linux",
    "macOS",
    "PRE",
    "Containers",
    "Network",
    "IaaS",
    "SaaS",
    "Office 365",
    "Azure AD",
    "Google Workspace",
]

_COMMENT_LIMIT = 500


class _Entry:
    """Accumulated alerts behind one (technique, tactic) layer entry."""

    __slots__ = ("direct", "via_sub")

    def __init__(self) -> None:
        self.direct: list[AlertMapping] = []
        self.via_sub: list[AlertMapping] = []

    @property
    def alerts(self) -> list[AlertMapping]:
        """Direct alerts first, then parent credits, deduplicated."""
        seen: set[str] = set()
        ordered: list[AlertMapping] = []
        for mapping in (*self.direct, *self.via_sub):
            if mapping.id not in seen:
                seen.add(mapping.id)
                ordered.append(mapping)
        return ordered


def build_layer(
    *,
    case_name: str,
    attack_version: str,
    mappings: Sequence[AlertMapping],
    parent_of: Mapping[str, str],
    own_tactics: Mapping[str, Sequence[str]],
    ruleset_hash: str = "0" * 64,
    generated_at: str | None = None,
    tool_version: str = APP_VERSION,
) -> dict[str, Any]:
    """An ATT&CK Navigator layer for one case.

    ``parent_of`` maps a sub-technique id to its parent; ``own_tactics``
    maps any technique id to the tactic shortnames the catalogue lists
    for it (used when an alert declared none).
    """
    entries: dict[tuple[str, str], _Entry] = {}
    for mapping in mappings:
        for attack_id in mapping.techniques:
            for tactic in _entry_tactics(mapping, attack_id, own_tactics):
                entries.setdefault((attack_id, tactic), _Entry()).direct.append(mapping)
            parent = parent_of.get(attack_id)
            if parent is None:
                continue
            for tactic in _entry_tactics(mapping, parent, own_tactics):
                entries.setdefault((parent, tactic), _Entry()).via_sub.append(mapping)
    techniques = [
        _entry_payload(attack_id, tactic, entry)
        for (attack_id, tactic), entry in sorted(entries.items())
    ]
    timestamp = generated_at or utc_now_iso()
    major = attack_version.split(".", 1)[0] if attack_version else ""
    return {
        "name": f"TriageLens - {case_name}",
        "versions": {
            "attack": major,
            "navigator": NAVIGATOR_VERSION,
            "layer": NAVIGATOR_LAYER_VERSION,
        },
        "domain": ATTACK_DOMAIN,
        "description": (
            f"Generated by TriageLens {tool_version} on {timestamp}. Ruleset {ruleset_hash}."
        ),
        "filters": {"platforms": list(_PLATFORMS)},
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "max",
            "showID": True,
            "showName": True,
            "showAggregateScores": False,
            "countUnscored": False,
        },
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#ffe766", "#ff6666"], "minValue": 0, "maxValue": 4},
        "legendItems": [],
        "metadata": [],
        "links": [],
        "showTacticRowBackground": False,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }


def _entry_tactics(
    mapping: AlertMapping, attack_id: str, own_tactics: Mapping[str, Sequence[str]]
) -> tuple[str, ...]:
    """Declared tactics when there are any, else the technique's own."""
    return mapping.tactics or tuple(own_tactics.get(attack_id, ()))


def _entry_payload(attack_id: str, tactic: str, entry: _Entry) -> dict[str, Any]:
    alerts = entry.alerts
    levels = [mapping.level for mapping in alerts]
    score = max((_NAVIGATOR_SCORES.get(level, 1) for level in levels), default=1)
    max_level = max(levels, key=lambda level: _NAVIGATOR_SCORES.get(level, 1), default="")
    titles = list(dict.fromkeys(mapping.rule_title for mapping in alerts))
    body = (
        f"{len(alerts)} alert{'' if len(alerts) == 1 else 's'}; "
        f"max level {max_level}; rules: {'; '.join(titles)}"
    )
    if not entry.direct and entry.via_sub:
        body = f"via sub-technique; {body}"
    return {
        "techniqueID": attack_id,
        "tactic": tactic,
        "score": score,
        "color": "",
        "comment": body[:_COMMENT_LIMIT],
        "enabled": True,
        "metadata": [],
        "links": [],
        "showSubtechniques": True,
    }


__all__ = ["build_layer"]
