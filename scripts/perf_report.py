"""Turn a pytest-benchmark run into ``docs/perf-results.md``.

Spec 09 section 8 requires benchmark results to be recorded with device
information. This script is the second half of ``make perf``: it reads the
``perf`` properties that ``backend/tests/perf`` records, and writes or updates the
results file.

Measurements are grouped into "measured now" and, when a spec-09 target cannot be
measured yet, "not yet measurable". The latter list is kept in
``docs/DECISIONS.md``; this script only records what was actually measured, so the
document can never claim a passing target that was never run.

Usage::

    python scripts/perf_report.py <results.json> [--out docs/perf-results.md]
"""

from __future__ import annotations

import argparse
import json
import platform
import sqlite3
import sys
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "perf-results.md"

# Human-readable notes for each measurement the harness produces.
NOTES: dict[str, str] = {
    "migrations.apply": "Applying the full migration set to an empty database.",
    "audit.append": "One audit row appended, including the hash chain extension.",
    "audit.verify": "Walking and re-hashing a full chain, reported per row.",
    "events.insert": "Insert in one transaction; FTS5 index upkeep included.",
    "events.filter_indexed": "Equality filter on an indexed column.",
    "events.fts_query": "MATCH query against the FTS5 index, LIMIT 50.",
    "api.health": "GET /api/health through the full middleware stack.",
    "windows_evtx.parse": "Parsing committed EVTX fixtures with the EVTX parser.",
    "windows_event_xml.parse": "Parsing a generated Event XML export with the XML parser.",
    "linux_syslog.parse": "Parsing a generated RFC 3164 auth log with the syslog parser.",
    "linux_auditd.parse": "Parsing generated multi-line audit groups with the auditd parser.",
    "web_access.parse": "Parsing a generated Apache combined access log with the access parser.",
    "fw_paloalto.parse": "Parsing a generated PAN-OS traffic CSV with the firewall parser.",
    "generic_csv.parse": "Parsing a generated Splunk CSV export through the generic profile parser.",
    "ioc.extract": "Tier-1 IOC extraction across representative events, decode passes included.",
}


#: Measurements that are naturally a throughput; the rest are latencies and get
#: no rate, because a per-operation rate would read as a duration.
THROUGHPUT = {
    "audit.append",
    "audit.verify",
    "events.insert",
    "windows_evtx.parse",
    "windows_event_xml.parse",
    "linux_syslog.parse",
    "linux_auditd.parse",
    "web_access.parse",
    "fw_paloalto.parse",
    "generic_csv.parse",
    "ioc.extract",
}


def _format_rate(measurement: dict[str, Any]) -> str:
    """Rows per second for throughput measurements, otherwise no rate."""
    if measurement["name"] not in THROUGHPUT:
        return "n/a"
    median = float(measurement["median"])
    if median <= 0:
        return "n/a"
    per = "records/s" if measurement.get("unit") == "s/record" else "rows/s"
    return f"{1.0 / median:,.0f} {per}"


def device_info() -> dict[str, str]:
    """Hardware and platform details recorded alongside the numbers."""
    import os

    return {
        "Platform": platform.platform(),
        "Machine": platform.machine(),
        "Processor": platform.processor() or "unknown",
        "CPU count": str(os.cpu_count() or 0),
        "Python": platform.python_version(),
        "Python build": platform.python_implementation(),
        "SQLite": sqlite3.sqlite_version,
    }


def render(measurements: Sequence[dict[str, Any]], generated: str) -> str:
    """The full markdown document for one run."""
    lines = [
        "# Performance results",
        "",
        "Generated by `scripts/perf_report.py` from a `make perf` run. Do not edit by",
        "hand: re-run the benchmark to refresh these numbers.",
        "",
        f"Recorded: {generated}",
        "",
        "## Device",
        "",
        "| Property | Value |",
        "|---|---|",
    ]
    for key, value in device_info().items():
        lines.append(f"| {key} | {value} |")

    lines += [
        "",
        "## Measured",
        "",
        "Times are milliseconds. Throughput applies only to the row-oriented",
        "measurements; latency measurements have no rate.",
        "",
        "| Measurement | Unit | Best | Median | Worst | Throughput | Samples |",
        "|---|---|---|---|---|---|---|",
    ]
    for measurement in measurements:
        lines.append(
            "| `{name}` | {unit} | {best} | {median} | {worst} | {rate} | {samples} |".format(
                name=measurement["name"],
                unit=measurement.get("unit", ""),
                best=f"{float(measurement['best']) * 1000:.3f} ms",
                median=f"{float(measurement['median']) * 1000:.3f} ms",
                worst=f"{float(measurement['worst']) * 1000:.3f} ms",
                rate=_format_rate(measurement),
                samples=measurement["samples"],
            )
        )

    lines += ["", "### What each measurement covers", ""]
    for name, note in NOTES.items():
        if any(entry["name"] == name for entry in measurements):
            lines.append(f"- `{name}` — {note}")

    lines += [
        "",
        "## Spec 09 section 8 targets not covered by this harness",
        "",
        "This harness measures storage, parsing, IOC and health primitives. The",
        "spec 09 section 8 end-to-end targets (multi-worker ingest throughput, a",
        "1M-event detection run within 5 minutes at \u2264 2 GB RSS, 5M-event API and FTS",
        "p95 latency, UI first paint, and a 10 GB ingest within 1.5 GB RSS) are not",
        "measured here and are recorded as not-run in `docs/DECISIONS.md` and",
        "`docs/COMPLIANCE.md` rather than estimated.",
        "",
        "The numbers above were recorded on the platform in the Device table, which is",
        "not the spec's reference laptop (8 cores, 16 GB, NVMe). Treat them as a",
        "baseline for regression detection, not as a target verdict.",
        "",
    ]
    return "\n".join(lines) + "\n"


def render_targets(targets: Sequence[dict[str, Any]], generated: str) -> str:
    """The verdict document for a ``make perf-e2e`` run."""
    lines = [
        "# End-to-end performance results",
        "",
        "Generated by `scripts/perf_report.py` from a `make perf-e2e` run. Do not",
        "edit by hand: re-run the target to refresh these numbers.",
        "",
        f"Recorded: {generated}",
        "",
        "## Device",
        "",
        "| Property | Value |",
        "|---|---|",
    ]
    for key, value in device_info().items():
        lines.append(f"| {key} | {value} |")

    lines += [
        "",
        "## Spec 09 section 8 targets",
        "",
        "| Target | Value | Limit | Result | Notes |",
        "|---|---|---|---|---|",
    ]
    for target in targets:
        result = "PASS" if target.get("passed") else "FAIL"
        operator = ">=" if target.get("comparator") == "min" else "<="
        unit = target.get("unit", "")
        lines.append(
            "| `{name}` | {value} {unit} | {op} {limit} {unit} | {result} | {note} |".format(
                name=target["name"],
                value=target["value"],
                unit=unit,
                op=operator,
                limit=target["limit"],
                result=result,
                note=target.get("note", ""),
            )
        )

    lines += [
        "",
        "A `FAIL` records the profiled bottleneck; it is not hidden and not",
        "estimated away. The `smoke` scale runs the same code paths at a smaller",
        "size and is a regression baseline, not the reference verdict; the spec",
        "targets are set for the reference laptop (8 cores, 16 GB, NVMe).",
        "",
        "The UI first-paint target (Alerts with 1,000 alerts under 1 s) is measured",
        "by the frontend Playwright harness, which owns a browser, and is recorded",
        "in `docs/DECISIONS.md` rather than here.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Read the collected results and write the results document."""
    parser = argparse.ArgumentParser(
        description="Write the performance results document."
    )
    parser.add_argument("results", type=Path, help="JSON file from the perf harness")
    parser.add_argument(
        "--kind",
        choices=("measurements", "targets"),
        default="measurements",
        help="render primitive measurements or end-to-end target verdicts",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output path")
    args = parser.parse_args(argv)

    if not args.results.is_file():
        print(f"no results file at {args.results}", file=sys.stderr)
        return 1

    payload = json.loads(args.results.read_text(encoding="utf-8"))
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    if args.kind == "targets":
        targets = payload.get("targets", [])
        if not targets:
            print(f"{args.results} contained no target verdicts", file=sys.stderr)
            return 1
        args.out.write_text(render_targets(targets, generated), encoding="utf-8")
        print(f"wrote {args.out} with {len(targets)} target verdicts")
        return 0

    measurements = payload.get("measurements", [])
    if not measurements:
        print(f"{args.results} contained no measurements", file=sys.stderr)
        return 1

    args.out.write_text(render(measurements, generated), encoding="utf-8")
    print(f"wrote {args.out} with {len(measurements)} measurements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
